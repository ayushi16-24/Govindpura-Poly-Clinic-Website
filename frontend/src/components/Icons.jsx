// Service ke naam se mil-ta-julta icon chuno (admin ko icon set nahi karna padta)
export const serviceGlyph = (title = "") => {
  const t = title.toLowerCase();
  if (/heart|cardi/.test(t)) return "heart";
  if (/lab|test|pathol|diagnos|blood/.test(t)) return "microscope";
  if (/pharm|medicine|drug/.test(t)) return "pill";
  if (/child|pediat|women|maternity|gyn|family|elder/.test(t)) return "users";
  if (/emergency|urgent|critical/.test(t)) return "pulse";
  if (/bed|ward|admission|inpatient/.test(t)) return "bed";
  return "stethoscope";
};
